"""Lists every menu class (a file that builds a SimpleGui or Screen) with how many other files refer to it, and writes
docs/UI_INVENTORY.md (M7). A class that nothing outside itself and the admin directory refers to is a candidate for
removal; nothing is removed by this script (rule: deleting dead classes needs the owner's approval).
Run from the repository root:  python scripts/ui-audit.py
"""
import os
import re

ROOT = 'src/main/java'
files = {}
for d, _, names in os.walk(ROOT):
    for f in names:
        if f.endswith('.java'):
            path = os.path.join(d, f)
            files[path] = open(path, encoding='utf8', errors='ignore').read()

menus = []
for path, text in files.items():
    if re.search(r'new SimpleGui\(|Screen\.chest\(|new SimpleGui ', text) and path.endswith('.java'):
        menus.append(path)

rows = []
for path in menus:
    name = os.path.basename(path)[:-5]
    pat = re.compile(r'\b' + re.escape(name) + r'\b')
    outside = []
    for other, text in files.items():
        if other == path:
            continue
        if pat.search(text):
            outside.append(os.path.basename(other)[:-5])
    non_dir = [o for o in outside if o not in ('AdminDirectoryGui', 'ChangelogCommands')]
    opens = len(re.findall(r'public static [\w<>\[\]]+ open\w*\(', files[path]))
    uses_back = bool(re.search(r'footer\(|\.back\(|Back', files[path]))
    rows.append((name, path.replace(os.sep, '/')[len(ROOT) + 1:], opens, len(outside), len(non_dir), uses_back, ', '.join(sorted(non_dir)[:4])))

rows.sort(key=lambda r: (r[4], r[0]))
out = [
    '# Menu inventory (M7)\n',
    'Generated by `scripts/ui-audit.py` from `src/main/java`: every class that builds a chest menu, how many other classes mention it, '
    'and how many of those are neither the admin directory nor the changelog commands. **Nothing was deleted**; a class with no '
    'real referrers is a candidate for removal that needs the owner\'s approval (HANDOFF.md, owner questions).\n',
    'Menu classes: %d. With no referrer except the admin directory or commands: %d.\n' % (len(rows), sum(1 for r in rows if r[4] == 0)),
    '| Class | Entry points | Referrers | Other than directory/commands | Back or footer in file | Referenced by (first four) |',
    '| --- | ---: | ---: | ---: | :---: | --- |',
]
for name, rel, opens, outside, non_dir, back, who in rows:
    out.append('| `%s` | %d | %d | %d | %s | %s |' % (rel, opens, outside, non_dir, 'yes' if back else '**no**', who))
open('docs/UI_INVENTORY.md', 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')
print(len(rows), 'menus;', sum(1 for r in rows if r[4] == 0), 'with no real referrer')
