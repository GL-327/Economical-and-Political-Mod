"""Lists every place that gives coins (giveCoins, giveCoinsQuiet, giveCoinsExact) with the method it is in and whether
that method mentions a cooldown, cap or once-only guard, and writes docs/ECONOMY_CAPS.md (M3, rule 4.4).

This is a text scan, not a proof: a site marked "no guard word found" may be limited by its caller, and a site marked
with a guard word may use it for something else. It exists to give the owner a short list to look at, not to change
any number. Run from the repository root:  python scripts/economy-audit.py
"""
import os
import re
import sys

ROOT = 'src/main/java'
GIVE = re.compile(r'\b(giveCoins|giveCoinsQuiet|giveCoinsExact)\s*\(')
METHOD = re.compile(r'^\s*(?:public|private|protected|static|final|synchronized|\s)*[\w<>\[\],.? ]+\s+(\w+)\s*\([^;]*\)\s*(?:throws [\w., ]+)?\s*\{\s*$')
GUARD = re.compile(r'cooldown|COOLDOWN|lastClaim|daily|perDay|PER_DAY|\bcap\b|CAP\b|MAX_|maxPer|limit|LIMIT|already|claimed|once|ready\(', re.I)
RETURNS = re.compile(r'refund|withdraw|cancel|cashout|cashOut|redeem|return|sell|payout|settle|sale|deposit|transfer|trade|expire', re.I)
ADMIN = re.compile(r'admin|grant|setBalance|command', re.I)


def enclosing(lines, index):
    for i in range(index, max(index - 400, -1), -1):
        m = METHOD.match(lines[i])
        if m and m.group(1) not in ('if', 'for', 'while', 'switch', 'catch', 'synchronized', 'return', 'new'):
            return m.group(1), i
    return '?', max(index - 40, 0)


rows = []
for d, _, files in os.walk(ROOT):
    for f in files:
        if not f.endswith('.java'):
            continue
        path = os.path.join(d, f)
        lines = open(path, encoding='utf8', errors='ignore').read().split('\n')
        for i, line in enumerate(lines):
            if not GIVE.search(line) or re.search(r'static\s+\w+\s+give', line):
                continue
            name, start = enclosing(lines, i)
            body = '\n'.join(lines[start:i + 1])
            guards = sorted(set(g.lower() for g in GUARD.findall(body)))
            if ADMIN.search(name) or 'Admin' in f:
                kind = 'admin'
            elif RETURNS.search(name):
                kind = 'returns coins taken earlier (by name)'
            else:
                kind = 'new coins (by name)'
            rel = path.replace(os.sep, '/')[len(ROOT) + 1:]
            rows.append((kind, rel, i + 1, name, guards))

kinds = ['new coins (by name)', 'returns coins taken earlier (by name)', 'admin']
out = [
    '# Coin sources and their guards (M3 audit, rule 4.4)\n',
    'Generated by `scripts/economy-audit.py` from a text scan of `src/main/java`. It is a list for the owner to read, not a proof: '
    '"guard words" are cooldown, cap, limit, daily, once, claimed and similar words found in the same method above the call. '
    'A site with none may still be limited by its caller; a site with some may use the word for something else. '
    'The kind is guessed from the method name. **No amount or limit was changed.** Every number behind these sites is DEFAULT, '
    'unapproved until the owner reviews it (HANDOFF.md, owner questions).\n',
    'Totals: %d sites, %d new-coin sites with no guard word found.\n' % (
        len(rows), sum(1 for r in rows if r[0] == kinds[0] and not r[4])),
]
for kind in kinds:
    sel = sorted((r for r in rows if r[0] == kind), key=lambda r: (bool(r[4]), r[1], r[2]))
    out.append('\n## %s (%d)\n' % (kind, len(sel)))
    out.append('| File:line | Method | Guard words in the method |')
    out.append('| --- | --- | --- |')
    for _, rel, line, name, guards in sel:
        out.append('| `%s:%d` | `%s` | %s |' % (rel, line, name, ', '.join(guards) if guards else '**none found**'))
open('docs/ECONOMY_CAPS.md', 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')
print(len(rows), 'sites')
sys.exit(0)
