"""For every Back button wired through footer(...) or Elements.back(...), checks that the menu it returns to mentions the menu it
leaves: a Back that leads to a class which never opens this one is suspect (M7). A text scan: Back buttons that go to a parent held
in a variable (openFrom) are skipped, because the parent is whoever called. Writes docs/UI_BACK_AUDIT.md.
Run from the repository root:  python scripts/ui-back-audit.py
"""
import os
import re

ROOT = 'src/main/java'
files = {}
for d, _, names in os.walk(ROOT):
    for f in names:
        if f.endswith('.java'):
            p = os.path.join(d, f)
            files[f[:-5]] = (p, open(p, encoding='utf8', errors='ignore').read())

# footer(gui, SIZE, player, () -> Target.method(...)) / .footer(() -> Target.method(...)) / back(() -> Target.method(...))
BACK = re.compile(r'(?:footer\([^;]*?|\.back\()\s*\(\)\s*->\s*(?:\{\s*)?(?:[\w.]*\.)?([A-Z]\w*)\.(\w+)\(', re.S)
SELF = re.compile(r'(?:footer\([^;]*?|\.back\()\s*\(\)\s*->\s*(?:\{\s*)?(?!\w+\.)(\w+)\(')

rows = []
for name, (path, text) in sorted(files.items()):
    for m in BACK.finditer(text):
        target = m.group(1)
        if target == name or target not in files:
            continue
        other = files[target][1]
        if not re.search(r'\b' + re.escape(name) + r'\b', other):
            line = text.count('\n', 0, m.start()) + 1
            rows.append((name, line, target, m.group(2)))

out = [
    '# Back buttons that lead to a menu which never opens this one (M7)\n',
    'Generated by `scripts/ui-back-audit.py`. A text scan: for each Back wired to `Target.method(...)`, the class `Target` should mention '
    'the class the button is in, because that is how the player got there. A hit is a place to look, not proof of a bug (a menu can be '
    'reached through a command, and a hub can be the declared parent of a screen opened from several places).\n',
    'Hits: %d.\n' % len(rows),
    '| Menu | Line | Back goes to | Method |',
    '| --- | ---: | --- | --- |',
]
for name, line, target, method in rows:
    out.append('| `%s` | %d | `%s` | `%s` |' % (name, line, target, method))
open('docs/UI_BACK_AUDIT.md', 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')
print(len(rows), 'hits')
