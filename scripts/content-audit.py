"""Lists every class that spawns entities (addFreshEntity, spawn) and whether the same class mentions a cap, a cleanup or a
despawn, and the switch that gates it, then writes docs/CONTENT_AUDIT.md (M6). A text scan, not a proof.
Run from the repository root:  python scripts/content-audit.py
"""
import os
import re

ROOT = 'src/main/java'
SPAWN = re.compile(r'\.addFreshEntity\(|\bspawn\s*\(|\.spawnAtLocation\(|EntityType\.[A-Z_]+\.create\(')
CAP = re.compile(r'\bMAX_[A-Z_]+|\bcap\b|\blimit\b|maxActive|MAX\b|\bmax[A-Z]\w*', re.I)
CLEAN = re.compile(r'discard\(|\.remove\(|despawn|cleanup|clearAll|onServerStop|SERVER_STOPPING|removeAll', re.I)
SWITCH = re.compile(r'FeatureSettings|features\.[a-z_]+|\.enabled\b|isEnabled\(')

rows = []
for d, _, names in os.walk(ROOT):
    for f in names:
        if not f.endswith('.java'):
            continue
        path = os.path.join(d, f)
        text = open(path, encoding='utf8', errors='ignore').read()
        spawns = len(re.findall(r'\.addFreshEntity\(', text))
        if spawns == 0:
            continue
        rows.append((f[:-5], path.replace(os.sep, '/')[len(ROOT) + 1:], spawns,
                     bool(CAP.search(text)), bool(CLEAN.search(text)), bool(SWITCH.search(text))))

rows.sort(key=lambda r: (r[3] and r[4], -r[2], r[0]))
out = [
    '# Content systems that spawn entities (M6 audit)\n',
    'Generated by `scripts/content-audit.py`: every class with an `addFreshEntity` call, and whether the same class mentions a cap '
    '(MAX_, limit, cap), a cleanup (discard, remove, despawn, server stop) and a switch (feature flag or enabled). A text scan, not a '
    'proof; a class marked "no" may be limited by its caller. Nothing was changed.\n',
    'Classes: %d. Without both a cap word and a cleanup word: %d.\n' % (len(rows), sum(1 for r in rows if not (r[3] and r[4]))),
    '| Class | Spawn calls | Cap word | Cleanup word | Switch word |',
    '| --- | ---: | :---: | :---: | :---: |',
]
for name, rel, n, cap, clean, sw in rows:
    out.append('| `%s` | %d | %s | %s | %s |' % (rel, n, 'yes' if cap else '**no**', 'yes' if clean else '**no**', 'yes' if sw else 'no'))
open('docs/CONTENT_AUDIT.md', 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')
print(len(rows), 'classes;', sum(1 for r in rows if not (r[3] and r[4])), 'without both')
